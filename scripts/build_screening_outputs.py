def clean(value):
    value = (value or "").replace("\n", " ")
    value = re.sub(r"[{}]", "", value)
    value = value.replace(r"\&", "&")
    return re.sub(r"\s+", " ", value).strip()


def parse_bib():
    text = BIB.read_text(encoding="utf-8")
    entries = [e for e in re.split(r"\n(?=@)", text) if e.strip().startswith("@")]
    parsed = []
    for entry in entries:
        key_match = re.search(r"@\w+\{([^,]+),", entry)
        if not key_match:
            continue
        fields = {"citation_key": key_match.group(1)}
        for name in ["title", "author", "year", "journal", "booktitle", "publisher", "institution", "doi", "url"]:
            match = re.search(rf"\n\s*{name}\s*=\s*\{{", entry, re.I)
            if not match:
                continue
            start = match.end()
            depth = 1
            index = start
            while index < len(entry) and depth:
                char = entry[index]
                if char == "\\":
                    index += 2
                    continue
                if char == "{":
                    depth += 1
                elif char == "}":
                    depth -= 1
                index += 1
            if depth == 0:
                fields[name] = clean(entry[start:index - 1])
        parsed.append(fields)
    return parsed


